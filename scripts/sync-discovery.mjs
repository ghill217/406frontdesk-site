#!/usr/bin/env node
/**
 * sync-discovery.mjs — generate src/_data/discoveryFields.json (GHL field key -> id)
 * for the /discovery/ form from the live GHL API.
 *
 * Same reason as sync-build-brief.mjs: a wrong field id does not throw. GHL accepts the
 * payload and silently drops that answer. So ids are pulled, never typed, and this
 * refuses to write a map that disagrees with the question bank in EITHER direction:
 *   - a `ghl` key in src/_data/discovery.json that GHL does not have  -> fail
 *   - an `exact: true` question whose options differ from the live picklist -> fail
 *     (these fields are SHARED with the /start/ application and the intake form, so
 *      the picklist is theirs too; a drifted option would be dropped on write)
 *   - a server-set field (answer card, verdict) missing from GHL -> fail
 *
 * Usage:
 *   node scripts/sync-discovery.mjs            # regenerate from the live API
 *   node scripts/sync-discovery.mjs --check    # fail if the file is out of date
 *
 * Reads the token from ~/.hivemind/ghl-406-pit.txt (outside the vault). Never prints it.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const LOCATION_ID = "To7tF3i6kQHNNNuJGqpQ";
const FOLDER = "NT4FYCBhrcIiZ2re3XQ7"; // "Problem Discovery", shared with /start/ and the intake tag-along
const TOKEN_FILE = join(homedir(), ".hivemind", "ghl-406-pit.txt");
const BANK = new URL("../src/_data/discovery.json", import.meta.url);
const OUT = new URL("../src/_data/discoveryFields.json", import.meta.url);

/** Written by the function, never shown on the form. */
const SERVER_SET = ["discovery_answer_card", "discovery_fit_verdict"];

let token;
try {
  token = readFileSync(TOKEN_FILE, "utf8").trim();
} catch {
  console.error(`Cannot read the GHL token at ${TOKEN_FILE}.`);
  console.error("This script only regenerates the field map; the site builds fine without it.");
  process.exit(2);
}

const res = await fetch(`https://services.leadconnectorhq.com/locations/${LOCATION_ID}/customFields`, {
  headers: { Authorization: `Bearer ${token}`, Version: "2021-07-28" },
});
if (!res.ok) {
  console.error(`GHL returned ${res.status}. Token scope or network problem.`);
  process.exit(2);
}
const live = ((await res.json()).customFields || []);
const byKey = new Map(live.map((f) => [f.fieldKey.replace(/^contact\./, ""), f]));

const bank = JSON.parse(readFileSync(BANK, "utf8"));
const problems = [];
const fields = {};

function take(key, why) {
  const f = byKey.get(key);
  if (!f) { problems.push(`${why}: GHL has no field with key "${key}"`); return null; }
  fields[key] = { id: f.id, type: f.dataType, name: f.name, inDiscoveryFolder: f.parentId === FOLDER };
  return f;
}

for (const step of bank.steps) {
  for (const q of step.questions) {
    if (!q.ghl) continue;
    for (const key of [].concat(q.ghl)) {
      const f = take(key, `question "${q.id}"`);
      if (!f) continue;
      const picklist = (f.picklistOptions || []).map((o) => (typeof o === "string" ? o : o.label ?? o.value));
      if (q.exact) {
        if (JSON.stringify(picklist) !== JSON.stringify(q.options)) {
          problems.push(`question "${q.id}" is exact but its options differ from the live picklist on "${key}":\n      form: ${JSON.stringify(q.options)}\n      GHL:  ${JSON.stringify(picklist)}`);
        }
      } else if (picklist.length) {
        problems.push(`question "${q.id}" writes free text into "${key}", which is a picklist in GHL. Mark it exact or pick a text field.`);
      }
    }
  }
}
for (const key of SERVER_SET) take(key, "server-set field");

if (problems.length) {
  console.error("Refusing to write a field map that does not match GHL:");
  problems.forEach((p) => console.error("  - " + p));
  process.exitCode = 1;
} else {
  const data = {
    note: "GENERATED by scripts/sync-discovery.mjs from the live GHL API. Do not hand-edit: a wrong field id is accepted silently by GHL and the answer is dropped.",
    locationId: LOCATION_ID,
    folderId: FOLDER,
    serverSet: SERVER_SET,
    fields,
  };
  const text = JSON.stringify(data, null, 2) + "\n";
  if (process.argv.includes("--check")) {
    const current = (() => { try { return readFileSync(OUT, "utf8"); } catch { return ""; } })();
    const norm = (t) => t.split(String.fromCharCode(13)).join(""); // autocrlf hands back CRLF on checkout
    if (norm(current) !== norm(text)) {
      console.error("src/_data/discoveryFields.json is STALE vs GHL. Run: node scripts/sync-discovery.mjs");
      process.exitCode = 1;
    } else {
      console.log(`discoveryFields.json matches GHL (${Object.keys(fields).length} fields).`);
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${Object.keys(fields).length} field ids (${SERVER_SET.length} server-set).`);
  }
}
